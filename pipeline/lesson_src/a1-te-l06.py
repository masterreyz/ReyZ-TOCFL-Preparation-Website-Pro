H("h-char", "Introduction to Chinese Characters — The Six Categories (六書 liùshū)", pages=[156, 157])
T("char1",
  "Traditionally, Chinese characters are sorted into six types, called the “six writings”, 六書 liùshū:",
  "1. Pictographs 象形 — simplified drawings of things: 山 mountain, 日 sun, 月 moon, 木 tree.",
  "2. Indicatives 指事 — a sign or mark points to an abstract idea: 上 above, 下 below, 本 “root” (a mark at the bottom of 木 tree).",
  "3. Compound ideographs 會意 — two or more parts combine into a new meaning: 明 bright (日 sun + 月 moon), 休 rest (人 person leaning on 木 a tree), 林 woods (two trees).",
  "4. Phono-semantic compounds 形聲 — one part hints at the meaning, the other at the sound. This is by far the largest group: 媽 mā (女 woman + 馬 mǎ for the sound), 晴 qíng sunny (日 + 青 qīng), 清 qīng clear (水 water + 青).",
  "5. Derivative cognates 轉注 — pairs of related characters that explain each other, such as 考 and 老, both once meaning “old”.",
  "6. Phonetic loans 假借 — a character borrowed for another word that sounded the same. 來, for example, first pictured a kind of wheat and was later borrowed for “to come”.")

