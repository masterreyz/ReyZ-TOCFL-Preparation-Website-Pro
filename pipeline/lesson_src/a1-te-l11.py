# III. Existential Subject with 有 yǒu
H("g3", "III. Existential Subject with 有 yǒu", level=3, pages=[259, 260])
T("g3-f",
  "Use: 有 introduces the existence of an indefinite subject; the following VP describes what that subject does. The subject in Chinese is usually definite, so when it is indefinite it must be preceded by 有. 有 is always negated with 沒.",
  "“有 + NP + 在 + location” means the same as “location + 有 + NP”, but the two differ in focus: 地上有一支手機 (‘The floor has a cellphone on it’) focuses on the floor, while 有一支手機在地上 (‘There is a cellphone on the floor’) focuses on the cellphone.")
