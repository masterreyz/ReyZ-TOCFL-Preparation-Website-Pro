# V. Inferior Comparison with 沒有…那麼/這麼
H("g5", "V. Inferior Comparison with 沒有 méiyǒu…那麼/這麼 nàme/zhème…", level=3, pages=[310, 311])
T("g5-f",
  "Use: A 沒有 B 那麼/這麼 + state verb says A is not as [adjective] as B. This pattern is almost always negative; 那麼/這麼 can sometimes be dropped. Its positive counterpart, A 有 B 那麼/這麼 + state verb, is rare except in 嗎 questions. Note the three-way contrast: A 跟 B 一樣 (equal, Lesson 13), A 沒有 B 那麼 (inferior), A 比 B (superior, Lesson 8). Questions use the A-not-A form (有沒有).")
