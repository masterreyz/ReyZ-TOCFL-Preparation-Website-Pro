# II. 是…的 (focus)
H("g2", "II. To Focus with 是 shì…的 de", level=3, pages=[280, 281])
T("g2-f",
  "Use: This pattern highlights one element in a sentence about a past event and marks it as the focus — the main message of the sentence. The focus marker 是 goes directly before the focused element, and 的 goes at the end of the sentence (Subject + 是 + Focus + Activity + 的). The object is often moved to the very front of the sentence.",
  "The focused element can be the subject, the time, the place, the manner, and occasionally the verb — but never the object. 是 can be omitted; the pattern can also ask a wh-question (who, when, how, where) about a past event, but it does not work when “what” is the object. 不 always goes before 是.")
